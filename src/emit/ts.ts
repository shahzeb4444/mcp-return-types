// `mcp-return-types emit --ts`: .typegen/schemas/<server>.json -> <out>/<server>.d.ts
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import type { SchemasFile } from "../infer/run.js";
import { SCHEMAS_FILE_VERSION } from "../infer/run.js";
import type { ToolInference } from "../infer/tool.js";
import { resultTypeNames, safeComment, typeOf } from "./tstype.js";

/** What the emitter needs of an inferred tool (a `ToolEntry` has all of it). */
export type EmitTool = Pick<ToolInference, "tool" | "unwrap" | "confidence" | "confidenceReasons" | "schema" | "samples"> &
  Partial<Pick<ToolInference, "unwrapCounts">>;

const UNWRAP_NOTE: Record<ToolInference["unwrap"], string> = {
  structuredContent: "the result's structuredContent",
  "json-text": "the text content parsed as JSON",
  text: "the text content as a plain string",
  none: "no text and no structuredContent, so nothing to type",
  mixed: "structuredContent, JSON text or plain text (it varied between calls)",
};

/** SPEC §3 rule 1, text | parsed union: plain text in some results, JSON text in others. */
const TEXT_OR_JSON_NOTE = "the text content parsed as JSON when it parses, else the text as a plain string (it varied between calls)";

function unwrapNote(tool: EmitTool): string {
  const paths = Object.keys(tool.unwrapCounts ?? {});
  if (tool.unwrap === "mixed" && paths.length === 2 && paths.includes("text") && paths.includes("json-text")) return TEXT_OR_JSON_NOTE;
  return UNWRAP_NOTE[tool.unwrap];
}

/** The `// ...` comment lines and the `type` declaration for one tool. */
export function emitToolType(tool: EmitTool, typeName: string, opts: { exported: boolean; notes?: boolean }): string {
  const lines: string[] = [];
  // `notes: false` is for the Code Mode stubs: the model sees the type and nothing else about how it was found.
  if (opts.notes !== false) {
    lines.push(`// ${safeComment(tool.tool)}: result is ${unwrapNote(tool)}`);
    if (tool.confidence === "low") {
      lines.push("// low confidence");
      if (tool.confidenceReasons.length > 0) lines.push(`// (${safeComment(tool.confidenceReasons.join("; "))})`);
    }
  }
  const body = tool.unwrap === "none" ? "unknown" : typeOf(tool.schema).text;
  lines.push(`${opts.exported ? "export " : ""}type ${typeName} = ${body};`);
  return lines.join("\n");
}

/** The whole .d.ts text for one server. Tools are in name order, so the output is stable. */
export function emitServerTs(file: Pick<SchemasFile, "server" | "tools">, version: string): string {
  const tools = Object.values(file.tools).sort((a, b) => (a.tool < b.tool ? -1 : a.tool > b.tool ? 1 : 0));
  const names = resultTypeNames(tools.map((t) => t.tool));
  const header = [
    `// Generated by mcp-return-types ${version} for server "${safeComment(file.server)}". Do not edit by hand.`,
    "// Optional keys (?) were missing in some results; `| null` means the value was null in some results.",
    "// Types are inferred from real traffic, so treat them as strong hints rather than a contract.",
  ];
  const blocks = tools.map((t) => emitToolType(t, names.get(t.tool) as string, { exported: true }));
  return `${header.join("\n")}\n\n${blocks.join("\n\n")}\n`;
}

export interface EmitRunResult {
  files: { server: string; file: string; tools: number }[];
}

export function runEmitTs(opts: { inDir: string; outDir: string; version: string; servers?: readonly string[] }): EmitRunResult {
  const schemasDir = path.join(opts.inDir, "schemas");
  const result: EmitRunResult = { files: [] };
  if (!existsSync(schemasDir)) return result;
  const names = readdirSync(schemasDir)
    .filter((f) => f.endsWith(".json"))
    .filter((f) => opts.servers === undefined || opts.servers.includes(f.slice(0, -".json".length)))
    .sort();
  for (const name of names) {
    let parsed: SchemasFile;
    try {
      parsed = JSON.parse(readFileSync(path.join(schemasDir, name), "utf8")) as SchemasFile;
    } catch {
      continue;
    }
    if (parsed.v !== SCHEMAS_FILE_VERSION || typeof parsed.tools !== "object" || parsed.tools === null) continue;
    mkdirSync(opts.outDir, { recursive: true });
    const outFile = path.join(opts.outDir, `${name.replace(/\.json$/, "")}.d.ts`);
    writeFileSync(outFile, emitServerTs(parsed, opts.version));
    result.files.push({ server: parsed.server, file: outFile, tools: Object.keys(parsed.tools).length });
  }
  return result;
}

